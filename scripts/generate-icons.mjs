import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import sharp from "sharp";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
);
const publicDir = path.join(repoRoot, "public");

// The icon set is regenerated from one square source. `favicon.ico` is not
// produced here: the only maintained-path ICO encoder for this shape shipped a
// deprecated/unmaintained transitive tree (request, har-validator, jimp 0.2),
// so the committed favicon.ico is kept as-is and refreshed by hand when the
// artwork changes.
const targets = [
  {file: "favicon-16x16.png", size: 16},
  {file: "favicon-32x32.png", size: 32},
  {file: "favicon-48x48.png", size: 48},
  // Flattened onto opaque white because iOS composites transparency onto black
  // when it stores a home-screen icon; this flatten is for iOS, not a style choice.
  {file: "apple-touch-icon.png", size: 180, flatten: true}
];

const sourceArg = process.argv.slice(2).find((arg) => !arg.startsWith("-"));
const sourcePath = path.resolve(
  repoRoot,
  sourceArg ?? path.join("public", "icon.png")
);
const dryRun = process.env.DRY_RUN === "1" || process.argv.includes("--dry");

function fail(message) {
  console.error(`generate-icons: ${message}`);
  process.exit(1);
}

let metadata;
try {
  metadata = await sharp(sourcePath).metadata();
} catch (error) {
  fail(
    `cannot read source ${path.relative(repoRoot, sourcePath) ?? sourcePath}: ${error.message}`
  );
}

if (!metadata.width || !metadata.height) {
  fail(
    `source ${path.relative(repoRoot, sourcePath)} has no raster dimensions`
  );
}

if (metadata.width !== metadata.height) {
  fail(
    `source is ${metadata.width}x${metadata.height}; expected a square source ` +
      `so the marks are not distorted`
  );
}

const largestTarget = Math.max(...targets.map((target) => target.size));
if (metadata.width < largestTarget) {
  fail(
    `source is ${metadata.width}x${metadata.height}; ${largestTarget}px is the ` +
      `largest generated size (apple-touch-icon.png) and the script refuses to upscale`
  );
}

const sourceLabel = path.relative(repoRoot, sourcePath);
console.log(`Source: ${sourceLabel} (${metadata.width}x${metadata.height})`);

for (const target of targets) {
  const label = `${path.join("public", target.file)} (${target.size}x${target.size}${target.flatten ? ", flattened on white" : ""})`;
  if (dryRun) {
    console.log(`Would write ${label}`);
    continue;
  }

  let pipeline = sharp(sourcePath).resize(target.size, target.size);
  if (target.flatten) {
    pipeline = pipeline.flatten({background: "#ffffff"});
  }

  await pipeline.png().toFile(path.join(publicDir, target.file));
  console.log(`Wrote ${label}`);
}

if (dryRun) {
  console.log("Dry run: no files written.");
} else {
  console.log("Done. favicon.ico is not regenerated by this script.");
}
